#!/bin/sh
# monerodato (fork-only): regenerate src/fcmp_pp/fcmp_pp_rust/vendor/ and
# src/fcmp_pp/fcmp_pp_rust/.cargo/config.toml from Cargo.lock.
#
# The vendor/ commit is exactly this script's output. To review it, run the script in
# a clean checkout (it needs the network) and check that
#   git status --porcelain --ignored src/fcmp_pp/fcmp_pp_rust
# prints nothing. Written for cargo 1.99.1; another cargo may lay files out differently.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
cd "$here/../src/fcmp_pp/fcmp_pp_rust"

rm -rf vendor .cargo/config.toml
mkdir -p .cargo
{
  echo "# Generated by scripts/vendor.sh (monerodato, fork-only). Do not edit."
  echo "# Cargo builds fcmp_pp_rust from the vendored sources only, without the network."
  echo
  echo "[net]"
  echo "offline = true"
  echo
  cargo vendor --locked --versioned-dirs vendor
} > .cargo/config.toml.tmp
mv .cargo/config.toml.tmp .cargo/config.toml

sh "$here/check-vendor-rev.sh"
